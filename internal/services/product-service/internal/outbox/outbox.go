// Package outbox implements the transactional outbox: domain events are written
// into an ordinary table in the same PostgreSQL transaction as the state change
// that produced them, and a relay publishes them to Kafka afterwards.
//
// The reason is a dual write. Publishing to Kafka directly from the request path
// means writing to two systems that cannot commit together: if the process dies
// after the product row commits but before the produce call returns, the event is
// gone and no read model will ever learn about the product. Publishing first has
// the mirror problem, an event for a change that then rolled back. Writing the
// event into the transaction that already exists removes the window entirely - the
// event exists if and only if the business row does.
//
// The guarantee this yields is at-least-once, not exactly-once. A relay that
// publishes and then crashes before recording the fact will publish again on
// restart, so consumers must be idempotent. That is the cheaper half of the
// problem to get right: duplication is handled by a key the consumer already
// stores, whereas a silently lost event has no recovery path short of a full
// database scan.
package outbox

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
	"time"

	"github.com/lib/pq"

	"product-service/internal/event"
)

// Store reads and writes the outbox table. It is a plain repository: the relay
// and the command handlers reach it through the service layer's interfaces, so
// tests can substitute a stub.
type Store struct {
	db *sql.DB
}

// NewStore returns a store backed by db.
func NewStore(db *sql.DB) *Store { return &Store{db: db} }

// Append writes the given events inside an existing transaction and returns them
// with the identifiers the database assigned.
//
// The caller must pass the transaction that carries the business change, not the
// pool: writing the events on their own connection would reopen exactly the gap
// this pattern exists to close.
func (s *Store) Append(ctx context.Context, tx *sql.Tx, records []event.Record) ([]event.Record, error) {
	if len(records) == 0 {
		return nil, nil
	}

	// One prepared statement reused for every row in the batch. The event id is
	// generated by the database so that it is a real UUID without pulling in a
	// uuid library, and so the relay and the consumer agree on one value.
	const insert = `
		INSERT INTO outbox_events (
			event_id, topic, event_type, aggregate_type, aggregate_id,
			partition_key, payload
		)
		VALUES (gen_random_uuid(), $1, $2, $3, $4, $5, $6)
		RETURNING event_id::text, occurred_at`

	stmt, err := tx.PrepareContext(ctx, insert)
	if err != nil {
		return nil, fmt.Errorf("prepare outbox insert: %w", err)
	}
	defer func() { _ = stmt.Close() }()

	appended := make([]event.Record, 0, len(records))
	for _, record := range records {
		var (
			eventID    string
			occurredAt time.Time
		)
		err := stmt.QueryRowContext(ctx,
			record.Topic, record.EventType, record.AggregateType,
			record.AggregateID, record.Key, record.Payload,
		).Scan(&eventID, &occurredAt)
		if err != nil {
			return nil, fmt.Errorf("insert outbox event %s: %w", record.EventType, err)
		}
		record.EventID = eventID
		record.OccurredAt = occurredAt
		appended = append(appended, record)
	}
	return appended, nil
}

// appendTo writes a single event on an existing transaction. Append batches
// through one prepared statement because it has several rows to write; this
// handles the one-row case the derived-event recorder has.
func appendTo(ctx context.Context, tx *sql.Tx, record event.Record) error {
	const insert = `
		INSERT INTO outbox_events (
			event_id, topic, event_type, aggregate_type, aggregate_id,
			partition_key, payload
		)
		VALUES (gen_random_uuid(), $1, $2, $3, $4, $5, $6)`

	if _, err := tx.ExecContext(ctx, insert,
		record.Topic, record.EventType, record.AggregateType,
		record.AggregateID, record.Key, record.Payload,
	); err != nil {
		return fmt.Errorf("insert outbox event %s: %w", record.EventType, err)
	}
	return nil
}

// ClaimQuery is the statement that reserves rows for publishing.
//
// It is exported so the tests exercise the statement the relay actually runs.
// A test asserting against a copy of this query verifies the copy: when the lease
// predicate was missing here, every test still passed, because the copy in
// claim_sql_test.go was a copy of the query as it had been, not as it was.
const ClaimQuery = `
	WITH candidates AS (
		SELECT id
		FROM outbox_events
		WHERE published_at IS NULL
		  AND failed_at IS NULL
		  AND next_attempt_at <= CURRENT_TIMESTAMP
		  AND (leased_until IS NULL OR leased_until <= CURRENT_TIMESTAMP)
		ORDER BY id
		LIMIT $1
		FOR UPDATE SKIP LOCKED
	)
	UPDATE outbox_events o
	SET leased_until = CURRENT_TIMESTAMP + ($2 * INTERVAL '1 millisecond')
	FROM candidates c
	WHERE o.id = c.id
	RETURNING o.id, o.event_id::text, o.topic, o.event_type, o.aggregate_type,
	          o.aggregate_id, o.partition_key, o.payload, o.occurred_at, o.attempts,
	          o.leased_until`

// Claim reserves up to batchSize due events for publishing and returns them.
//
// The claim is a single statement, so it commits on its own and the row locks
// are released before anything is sent to Kafka. Holding them across the network
// call would block every other relay and any command that touched the same
// rows. A short lease instead: leased_until marks the row as taken, and if the
// relay dies mid-publish the lease expires and another one picks the event up.
//
// FOR UPDATE SKIP LOCKED is what lets several relay replicas share one table.
// Rows another replica has claimed are skipped rather than waited on, so they
// divide the work without a lock manager.
//
// SKIP LOCKED alone is not enough, because the claim commits before the publish
// happens. Once it commits there is no lock left for a second relay to skip, so
// the lease predicate is what actually stops two relays publishing the same event.
// Without it every relay claimed every pending row: the column was written on
// claim and then never read.
//
// attempts is deliberately not touched here. It counts failed publishes, and a
// failure is something the relay can see; a claim is not a publish attempt, and
// incrementing on claim made a contended row exhaust its budget while publishing
// successfully every time.
func (s *Store) Claim(ctx context.Context, batchSize int, lease time.Duration) ([]event.Record, error) {
	rows, err := s.db.QueryContext(ctx, ClaimQuery, batchSize, lease.Milliseconds())
	if err != nil {
		return nil, fmt.Errorf("claim outbox events: %w", err)
	}
	defer func() { _ = rows.Close() }()

	claimed := make([]event.Record, 0, batchSize)
	for rows.Next() {
		var record event.Record
		// The topic is read back from the row rather than assumed from the event
		// type: it is stored per row, so a service that adds a second stream does
		// not need a schema change, and a relay that assumed one topic would send
		// everything to the wrong place.
		if err := rows.Scan(
			&record.ID, &record.EventID, &record.Topic, &record.EventType,
			&record.AggregateType, &record.AggregateID, &record.Key,
			&record.Payload, &record.OccurredAt, &record.Attempts, &record.LeaseUntil,
		); err != nil {
			return nil, fmt.Errorf("claim outbox events: scan row: %w", err)
		}
		claimed = append(claimed, record)
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("claim outbox events: %w", err)
	}
	return claimed, nil
}

// leaseGuard matches only the rows this relay still holds.
//
// The lease value returned by Claim is echoed back here, so the update becomes a
// compare-and-swap: if the lease expired and another relay re-claimed the row, the
// stored leased_until no longer matches and this relay's bookkeeping is discarded
// rather than overwriting the new holder's. Without it, a relay that stalled
// through its lease would mark a row published on the strength of a publish the
// next relay had not made.
const leaseGuard = `leased_until = $2`

// MarkPublished records that the broker acknowledged the given outbox rows.
func (s *Store) MarkPublished(ctx context.Context, claimed []event.Record) error {
	if len(claimed) == 0 {
		return nil
	}

	// The ids and their lease values are paired rather than passed as one array:
	// they are read together, and a single bulk statement cannot compare each row
	// against its own lease.
	const query = `
		UPDATE outbox_events o
		SET published_at = CURRENT_TIMESTAMP, leased_until = NULL, last_error = NULL
		FROM unnest($1::bigint[], $2::timestamptz[]) AS held(id, lease)
		WHERE o.id = held.id AND o.leased_until = held.lease`

	ids, leases := idsAndLeases(claimed)
	if _, err := s.db.ExecContext(ctx, query, pq.Array(ids), pq.Array(leases)); err != nil {
		return fmt.Errorf("mark outbox events published: %w", err)
	}
	return nil
}

// idsAndLeases splits claimed records into the parallel arrays the lease-guarded
// statements bind.
func idsAndLeases(claimed []event.Record) ([]int64, []time.Time) {
	ids := make([]int64, 0, len(claimed))
	leases := make([]time.Time, 0, len(claimed))
	for _, record := range claimed {
		ids = append(ids, record.ID)
		leases = append(leases, record.LeaseUntil)
	}
	return ids, leases
}

// Reschedule records a failed publish and pushes the row's next attempt out to
// retryAt, so a broker that is struggling is not hammered by a tight loop.
//
// This is where attempts is incremented, because this is the point at which a
// publish has actually been tried and failed.
func (s *Store) Reschedule(ctx context.Context, record event.Record, cause error, retryAt time.Time) error {
	const query = `
		UPDATE outbox_events
		SET next_attempt_at = $3, leased_until = NULL, last_error = $4,
		    attempts = attempts + 1
		WHERE id = $1 AND ` + leaseGuard

	if err := s.updateOutcome(ctx, query, record, cause, []any{retryAt}); err != nil {
		return fmt.Errorf("reschedule outbox event %d: %w", record.ID, err)
	}
	return nil
}

// Fail marks an event as permanently undeliverable after MaxAttempts. It stops
// being claimed, which is what keeps one poison event from blocking the queue
// forever, but it does not delete it: the row is the audit trail that says this
// change never reached the read model.
//
// attempts is incremented here too. A row abandoned for exhausting its budget has
// failed every attempt it was given, so its count has to reflect the last one.
func (s *Store) Fail(ctx context.Context, record event.Record, cause error) error {
	const query = `
		UPDATE outbox_events
		SET failed_at = CURRENT_TIMESTAMP, leased_until = NULL, last_error = $3,
		    attempts = attempts + 1
		WHERE id = $1 AND ` + leaseGuard

	if err := s.updateOutcome(ctx, query, record, cause, nil); err != nil {
		return fmt.Errorf("fail outbox event %d: %w", record.ID, err)
	}
	return nil
}

// updateOutcome runs one lease-guarded terminal update. The lease is bound as $2 by
// every caller, and the remaining arguments are appended, so the guard cannot be
// forgotten on a new statement.
func (s *Store) updateOutcome(ctx context.Context, query string, record event.Record, cause error, extra []any) error {
	args := make([]any, 0, 2+len(extra))
	args = append(args, record.ID, record.LeaseUntil)
	args = append(args, extra...)
	args = append(args, causeMessage(cause))

	if _, err := s.db.ExecContext(ctx, query, args...); err != nil {
		return err
	}
	return nil
}

// causeMessage renders a failure for the last_error column.
func causeMessage(cause error) string {
	if cause == nil {
		return "unknown error"
	}
	return cause.Error()
}

// Stats is a snapshot of the outbox, used by the readiness and status endpoints.
type Stats struct {
	// Pending is how many events are waiting to be published.
	Pending int64
	// Failed is how many exhausted their attempts and need a human.
	Failed int64
	// OldestPending is the age of the oldest unpublished event, which is the
	// number that matters: it is how far the read model can be behind.
	OldestPending *time.Duration
}

// Stats reports how much work is outstanding. It is one aggregate query, so it is
// cheap enough to call from a health endpoint.
func (s *Store) Stats(ctx context.Context) (Stats, error) {
	const query = `
		SELECT
			COUNT(*) FILTER (WHERE published_at IS NULL AND failed_at IS NULL),
			COUNT(*) FILTER (WHERE failed_at IS NOT NULL),
			MIN(occurred_at) FILTER (WHERE published_at IS NULL AND failed_at IS NULL)
		FROM outbox_events`

	var (
		stats    Stats
		oldest   sql.NullTime
		oldestAt time.Time
	)
	err := s.db.QueryRowContext(ctx, query).Scan(&stats.Pending, &stats.Failed, &oldest)
	switch {
	case errors.Is(err, sql.ErrNoRows):
		// An empty table reports one row of NULLs rather than no rows.
		return Stats{}, nil
	case err != nil:
		return Stats{}, fmt.Errorf("outbox stats: %w", err)
	}
	if oldest.Valid {
		oldestAt = oldest.Time
		age := time.Since(oldestAt)
		stats.OldestPending = &age
	}
	return stats, nil
}

// Backoff returns how long to wait before the next attempt of an event that has
// already failed the given number of times.
//
// The wait grows exponentially up to a ceiling. A broker that is down should be
// retried occasionally, not on every tick of the relay loop, and an unbounded
// doubling would push a recovered event's delivery hours into the future.
func Backoff(attempts int) time.Duration {
	const base = 2 * time.Second

	if attempts < 1 {
		attempts = 1
	}
	// Capped before shifting rather than by a loop, so a large attempt count
	// cannot overflow the duration and produce a negative wait.
	if attempts > 20 {
		return maxBackoff
	}
	wait := base << (attempts - 1)
	if wait > maxBackoff {
		return maxBackoff
	}
	return wait
}
