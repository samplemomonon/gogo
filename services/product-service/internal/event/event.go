// Package event defines the domain events product-service publishes to Kafka and
// the envelope they travel in.
//
// Events are the contract between the write side (product-service) and the read
// side (product-listing-service). They are deliberately a separate set of types
// from internal/model: the model may be refactored freely, but a published event
// once consumed by another service can never change shape without a new version
// of its event type.
//
// Two choices are worth calling out, because they drive the whole design.
//
// First, events carry a full snapshot of the aggregate rather than a diff. A
// snapshot is self-contained, so the consumer never has to read the producer's
// database to interpret it, and re-applying the same event twice produces the
// same state. A diff would be smaller but would make the consumer depend on
// having seen every earlier event in the right order, which is exactly the
// property an at-least-once transport does not guarantee.
//
// Second, every event for one product uses that product's id as its Kafka
// message key. Kafka only guarantees ordering within a partition, so keying by
// aggregate id is what guarantees that product.created is always seen before the
// product.updated that follows it, while unrelated products still spread across
// partitions and consume them in parallel.
package event

import (
	"encoding/json"
	"fmt"
	"time"
)

const (
	// Topic is the Kafka topic every product event is published to. The trailing
	// version is the topic's schema version, which is why a breaking change means
	// a new topic rather than a new field.
	Topic = "product.events.v1"

	// SchemaVersion is the version of the envelope written into each message and
	// repeated in a header, so a consumer can reject a shape it does not
	// understand instead of misreading it.
	SchemaVersion = 1
)

// AggregateType names the entity an event is about. It is part of the Kafka
// record header rather than only the body, so routing can happen before the
// payload is parsed.
//
// Every event this service emits, including the ones about a variant, names the
// product as its aggregate. A variant has no meaning without its product, and
// grouping it here is what keeps every event about one product in the order those
// events happened.
const AggregateType = "product"

// The event types this service emits. They are fully qualified with the
// aggregate and a version, so `product.v1.product.created` and a hypothetical
// `product.v2.product.created` can coexist in the same topic during a migration.
const (
	TypeProductCreated       = "product.v1.product.created"
	TypeProductUpdated       = "product.v1.product.updated"
	TypeProductDeleted       = "product.v1.product.deleted"
	TypeProductStockAdjusted = "product.v1.product.stock_adjusted"

	TypeVariantCreated = "product.v1.variant.created"
	TypeVariantUpdated = "product.v1.variant.updated"
	TypeVariantDeleted = "product.v1.variant.deleted"
)

// Envelope wraps every payload. Consumers switch on EventType and decode Payload
// into the matching struct, so the envelope is the only part of the message whose
// shape they must understand before they can route.
type Envelope struct {
	// EventID is a UUID generated by the database when the event is written to
	// the outbox. It is the deduplication key: a consumer that sees the same ID
	// twice knows it is looking at a redelivery of one event, not two events.
	EventID string `json:"event_id"`
	// EventType is one of the Type* constants above.
	EventType string `json:"event_type"`
	// SchemaVersion is the envelope version this message was written with.
	SchemaVersion int `json:"schema_version"`
	// AggregateType and AggregateID identify what the event is about.
	AggregateType string `json:"aggregate_type"`
	AggregateID   int64  `json:"aggregate_id"`
	// OccurredAt is when the state change committed, not when the relay
	// published it, so a consumer can reason about ordering in wall-clock terms
	// without mistaking relay lag for a slow write.
	OccurredAt time.Time `json:"occurred_at"`
	// Payload holds the event-specific body, encoded as JSON.
	Payload json.RawMessage `json:"payload"`
}

// Record is an event together with the outbox bookkeeping the relay needs to
// publish it. It is what the repository returns and the relay consumes, so the
// two halves of the outbox agree on one type.
type Record struct {
	// ID is the outbox row's sequence number. Rows are claimed in this order, so
	// events are published roughly in the order they were committed.
	ID int64
	// EventID is the deduplication key, generated when the row was written.
	EventID string
	// Topic is the Kafka topic to publish to. It is stored per row rather than
	// assumed, so a service that adds a second topic does not need a schema
	// change to carry it.
	Topic string
	// EventType, AggregateType and AggregateID come from the envelope.
	EventType     string
	AggregateType string
	AggregateID   int64
	// Key is the Kafka message key. It is the aggregate id as a string, so every
	// event about one product lands on one partition and stays ordered.
	Key string
	// Payload is the encoded body, stored verbatim in the outbox row.
	Payload []byte
	// OccurredAt is when the state change committed.
	OccurredAt time.Time
	// Attempts counts publish attempts that have FAILED so far.
	//
	// It is incremented when a publish fails, not when a row is claimed. Those are
	// different things: a claim is this relay picking the row up, and a row can be
	// claimed several times without the broker ever being troubled. Counting claims
	// made the budget measure relay contention rather than delivery trouble, so a
	// busy relay abandoned events that had published successfully.
	Attempts int
	// LeaseUntil is the instant this claim's lease expires. The relay passes it
	// back when recording the outcome, and the store matches on it so a relay
	// whose lease expired cannot overwrite the bookkeeping of the relay that took
	// over the row.
	LeaseUntil time.Time
}

// New builds a Record from an event type, aggregate and payload, encoding the
// payload as JSON. The event id and timestamps are left empty: the database
// assigns the id when the row is inserted, and the relay reads the rest back.
func New(eventType string, aggregateID int64, payload any) (Record, error) {
	return newRecord(eventType, aggregateID, aggregateID, payload)
}

// NewVariantEvent builds a Record for something that belongs to a product but is
// not the product itself, such as a variant.
//
// The aggregate is the variant, so a consumer can tell what the event is about,
// but the partition key is the parent product. That is deliberate: keying by the
// variant would spread a product's events across partitions, and Kafka only
// guarantees order within one partition. A consumer could then see a product
// snapshot republished after a variant was added before it saw the variant event
// that snapshot already accounts for. Keying by the product removes that
// possibility, at the cost of a product's events being serialised against each
// other, which is the ordering they need anyway.
func NewVariantEvent(eventType string, variantID, productID int64, payload any) (Record, error) {
	return newRecord(eventType, variantID, productID, payload)
}

// newRecord assembles a record, taking the aggregate and the partition key
// separately so the two can differ.
func newRecord(eventType string, aggregateID, partitionKey int64, payload any) (Record, error) {
	body, err := json.Marshal(payload)
	if err != nil {
		return Record{}, fmt.Errorf("encode %s payload: %w", eventType, err)
	}
	return Record{
		Topic:         Topic,
		EventType:     eventType,
		AggregateType: AggregateType,
		AggregateID:   aggregateID,
		Key:           fmt.Sprintf("%d", partitionKey),
		Payload:       body,
	}, nil
}

// Marshal returns the envelope as it is published to Kafka.
func (r Record) Marshal() ([]byte, error) {
	body, err := json.Marshal(Envelope{
		EventID:       r.EventID,
		EventType:     r.EventType,
		SchemaVersion: SchemaVersion,
		AggregateType: r.AggregateType,
		AggregateID:   r.AggregateID,
		OccurredAt:    r.OccurredAt,
		Payload:       json.RawMessage(r.Payload),
	})
	if err != nil {
		return nil, fmt.Errorf("encode %s envelope: %w", r.EventType, err)
	}
	return body, nil
}

// ProductDeletedPayload is the body of TypeProductDeleted. A delete carries no
// snapshot: there is nothing left to describe, and the consumer already has the
// row it needs to remove.
type ProductDeletedPayload struct {
	ID int64 `json:"id"`
}

// ProductStockAdjustedPayload is the body of TypeProductStockAdjusted. It carries
// the resulting stock rather than the delta, because a delta would require the
// consumer to have seen every previous adjustment, while the resulting value is
// the whole truth about the only field that changed.
type ProductStockAdjustedPayload struct {
	ID    int64 `json:"id"`
	Stock int64 `json:"stock"`
	Delta int64 `json:"delta"`
}

// VariantDeletedPayload is the body of TypeVariantDeleted.
type VariantDeletedPayload struct {
	ProductID int64 `json:"product_id"`
	VariantID int64 `json:"variant_id"`
}
