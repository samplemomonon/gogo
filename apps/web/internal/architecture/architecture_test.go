// Package architecture_test pins the load-bearing import boundaries of the
// gogo codebase so they cannot silently decay. Every rule asserted here is
// stated, with its rationale, in ARCHITECTURE.md §2.
//
// # Graph source
//
// The rules read a committed snapshot of the import graph, import_graph.txt:
// one line per Go package, its direct main-repo imports. Test-only imports are
// excluded — tests may bridge worlds, production code may not.
//
// The snapshot exists so the rules read a committed file rather than shelling
// out to the toolchain. A snapshot can go stale, and a stale snapshot is worse
// than no check at all: it would quietly stop reflecting the code while still
// reporting success. TestImportGraphIsCurrent therefore re-derives the graph
// from the working tree on every run and fails on any difference.
//
// # Why `go list` and not the Bazel BUILD files
//
// This previously derived the graph by parsing the `deps` attribute of each
// go_library in the Bazel BUILD files, on the theory that BUILD files are
// declared inputs and so work under `bazel test //...`. That theory never paid
// out, and the mechanism rotted:
//
//   - Bazel is not installed in this checkout, and there is no MODULE.bazel or
//     WORKSPACE file. Nothing runs `bazel test`.
//   - Only 44 BUILD.bazel files remain, covering 43 packages — cmd, contracts,
//     modules/auth, modules/reporting, and the home/profile/seller pages. Every
//     other package, including all of internal/shared and internal/bootstrap,
//     has none.
//   - So the derived graph covered roughly a third of the repo while the
//     committed snapshot held 119 packages. The staleness gate had been failing,
//     which means the snapshot had been drifting with nothing to notice.
//
// The BUILD files were themselves generated by Gazelle from `go list`, so `go
// list` is the upstream source, not a substitute for it. Reading it directly
// gives full coverage, needs no build system, and cannot rot the same way. The
// price is that the regeneration half needs a Go toolchain and therefore cannot
// run in a sandbox holding only declared srcs — which is the trade this repo
// already makes in `make check`, and which costs nothing while no Bazel run
// exists to be incompatible with.
package architecture_test

