package ui

import (
	"bytes"
	"errors"
	"html/template"
	"log/slog"
	"net/http"

	"github.com/go-chi/chi/v5"
	"github.com/yuin/goldmark"

	"gogo/internal/shared/web/navigation"
)

type PageHandler struct {
	reader Reader
	logger *slog.Logger
}

func NewPageHandler(reader Reader, logger *slog.Logger) *PageHandler {
	return &PageHandler{reader: reader, logger: logger}
}

func (h *PageHandler) RegisterRoutes(r chi.Router) {
	r.Get("/pages/{slug}", h.handle)
}

func (*PageHandler) Nav() []navigation.Item { return nil }

func (h *PageHandler) handle(w http.ResponseWriter, r *http.Request) {
	if h.reader == nil {
		http.NotFound(w, r)
		return
	}
	page, err := h.reader.ReadPublished(r.Context(), chi.URLParam(r, "slug"))
	switch {
	case errors.Is(err, ErrNotFound):
		http.NotFound(w, r)
		return
	case err != nil:
		h.logger.Error("editorial page unavailable", "slug", chi.URLParam(r, "slug"), "error", err)
		http.Error(w, "Halaman konten sementara tidak tersedia.", http.StatusServiceUnavailable)
		return
	}
	view, err := renderPage(page)
	if err != nil {
		h.logger.Error("editorial page rendering failed", "slug", page.Slug, "error", err)
		http.Error(w, "Halaman konten sementara tidak tersedia.", http.StatusInternalServerError)
		return
	}
	w.Header().Set("Content-Type", "text/html; charset=utf-8")
	w.Header().Set("Cache-Control", "public, max-age=60, stale-while-revalidate=30")
	w.WriteHeader(http.StatusOK)
	if err := pageTemplate.Execute(w, view); err != nil {
		h.logger.Error("editorial page response failed", "slug", page.Slug, "error", err)
	}
}

type renderedPage struct {
	Title  string
	Blocks []renderedBlock
}

type renderedBlock struct {
	Type     string
	Title    string
	Body     template.HTML
	ImageURL string
	ImageAlt string
	Label    string
	Href     string
	Items    []renderedFAQItem
}

type renderedFAQItem struct {
	Question string
	Answer   template.HTML
}

func renderPage(page Page) (renderedPage, error) {
	if err := page.Validate(); err != nil {
		return renderedPage{}, err
	}
	view := renderedPage{Title: page.Title, Blocks: make([]renderedBlock, 0, len(page.Blocks))}
	for _, block := range page.Blocks {
		item := renderedBlock{
			Type: block.Type, Title: block.Title, ImageURL: block.ImageURL,
			ImageAlt: block.ImageAlt, Label: block.Label, Href: block.Href,
		}
		if block.Type == "markdown" {
			html, err := markdownHTML(block.Body)
			if err != nil {
				return renderedPage{}, err
			}
			item.Body = html
		}
		if block.Type == "faq" {
			item.Items = make([]renderedFAQItem, 0, len(block.Items))
			for _, faq := range block.Items {
				answer, err := markdownHTML(faq.Answer)
				if err != nil {
					return renderedPage{}, err
				}
				item.Items = append(item.Items, renderedFAQItem{Question: faq.Question, Answer: answer})
			}
		}
		view.Blocks = append(view.Blocks, item)
	}
	return view, nil
}

func markdownHTML(source string) (template.HTML, error) {
	var output bytes.Buffer
	if err := goldmark.New().Convert([]byte(source), &output); err != nil {
		return "", err
	}
	// Goldmark's default renderer escapes raw HTML and rejects unsafe URL
	// schemes. Do not enable renderer/html.WithUnsafe for CMS-authored text.
	return template.HTML(output.String()), nil //nolint:gosec // output is generated by the safe Goldmark renderer above
}

var pageTemplate = template.Must(template.New("editorial-page").Parse(`<!doctype html>
<html lang="id"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>{{.Title}}</title><meta name="robots" content="index,follow"><link rel="stylesheet" href="/assets/css/output.css"></head>
<body class="min-h-screen bg-base-200 text-base-content"><main class="container mx-auto max-w-4xl px-4 py-10 sm:py-16"><article class="space-y-8"><header class="rounded-2xl border border-base-300 bg-base-100 p-6 shadow-sm sm:p-10"><h1 class="text-3xl font-bold tracking-tight sm:text-4xl">{{.Title}}</h1></header>{{range .Blocks}}<section class="rounded-2xl border border-base-300 bg-base-100 p-6 shadow-sm sm:p-8">{{if .Title}}<h2 class="mb-5 text-2xl font-semibold">{{.Title}}</h2>{{end}}
{{if or (eq .Type "hero") (eq .Type "banner")}}{{if .ImageURL}}<img class="mb-5 max-h-96 w-full rounded-xl object-cover" src="{{.ImageURL}}" alt="{{.ImageAlt}}">{{end}}{{end}}
{{if eq .Type "markdown"}}<div class="space-y-4 leading-7">{{.Body}}</div>{{end}}
{{if eq .Type "faq"}}<div class="space-y-3">{{range .Items}}<details class="collapse collapse-arrow rounded-xl border border-base-300 bg-base-100"><summary class="collapse-title font-semibold">{{.Question}}</summary><div class="collapse-content leading-7">{{.Answer}}</div></details>{{end}}</div>{{end}}
{{if eq .Type "cta"}}<p><a class="btn btn-primary" href="{{.Href}}">{{.Label}}</a></p>{{end}}</section>{{end}}</article></main></body></html>`))

// Compile-time interface assertion keeps content routes aligned with the
// gateway page contract without introducing a dependency on the shell.
var _ interface {
	RegisterRoutes(chi.Router)
	Nav() []navigation.Item
} = (*PageHandler)(nil)
